"""Render the results ledger (numbers.md) from data/numbers.json.

The manuscript quotes only numbers that this script prints, so the prose and the
replay archives cannot drift apart.  Run from the project root:

    python scripts/write_ledger.py
"""
from __future__ import annotations

import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if hasattr(sys.stdout, "buffer"):
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

METHOD_ORDER = ["U_0", "U_-1/3", "U_+1/3", "C", "R", "J", "online", "oracle"]
KS = ["5", "9", "15"]
JOINT_BUDGETS = ["5", "9", "15", "full_N"]


def fmt(x, nd=4):
    if x is None:
        return "n/a"
    return f"{x:.{nd}f}"


def main() -> None:
    d = json.loads((ROOT / "data" / "numbers.json").read_text(encoding="utf-8"))
    p = d["protocol"]
    out: list[str] = []
    w = out.append

    w("# Results ledger: error-constrained imaging schedules")
    w("")
    w("Generated by `scripts/write_ledger.py` from `data/numbers.json`, which")
    w("`scripts/derive_numbers.py` recomputes from the replay archives. Every number")
    w("used in the archived result ledger appears in this file.")
    w("")

    w("## 1. Frozen protocol")
    w("")
    w(f"- Window gates: `{json.dumps(p['window_gates'], sort_keys=True)}`")
    w(f"- Joint tolerances: tau_A = {p['joint_tolerances']['area_pp']} pp of area "
      f"fraction, tau_N = {p['joint_tolerances']['leaves']} leaves")
    w(f"- Worthwhile-difference gate: {p['worthwhile_difference_pp']} pp")
    w(f"- Budgets K: {p['budgets']}")
    w(f"- Phase offsets: {[round(x, 6) for x in p['phases']]}")
    w(f"- Random repeats per seed: {p['random_repeats']}")
    w(f"- Planned replay units per window (all strategies, incl. full-N): "
      f"{p['planned_units_per_window']}")
    w(f"- Online controller: `{json.dumps(p['online_parameters'], sort_keys=True)}`")
    w(f"- Replay seed: {p['seed']}")
    w(f"- Roles used for these numbers: {', '.join(p['selection_roles'])}")
    w(f"- Physical scale: {p['physical_roi']}")
    w(f"- Replay source SHA-256: `{p['source_sha256']}`")
    w(f"- Inventory SHA-256: `{p['inventory_sha256']}`")
    w("")

    f = d["gt_funnel"]
    w("## 2. Feasibility funnel (development roles)")
    w("")
    w(f"- Inventory rows scanned: {f['inventory_rows']:,}")
    w(f"- Development plants: {f['development_plants']}")
    w(f"- Window-eligible: {f['window_eligible']} "
      f"({100 * f['window_share_of_development']:.1f}%)")
    w(f"- Area-eligible: {f['area_eligible']} ({100 * f['area_share_of_development']:.1f}%)")
    w(f"- Further area-dimension exclusions: {f['area_dimension_exclusions']}")
    w(f"- Duplicate timestamps: {f['duplicate_timestamps']}; conflicts: {f['timestamp_conflicts']}; "
      f"naive timestamps assumed UTC: {f['naive_timestamps']:,}")
    w("- First-reason exclusions (plants, share of development plants):")
    for key in sorted(f["exclusions"], key=lambda k: -f["exclusions"][k]):
        w(f"  - {key}: {f['exclusions'][key]} "
          f"({100 * f['exclusion_share'][key]:.1f}%)")
    w("- Window-eligible by role: " + ", ".join(
        f"{k}={v}" for k, v in sorted(f["window_roles"].items())))
    w("- Area-eligible by role: " + ", ".join(
        f"{k}={v}" for k, v in sorted(f["area_window_roles"].items())))
    w("")
    dens = d["gt_window_density"]
    w("Density of the windows the gates kept (min / median / max over plants):")
    for key in ("window_eligible", "area_eligible"):
        g = dens[key]
        w(f"- {key} ({g['plants']} plants): N = {g['N']['min']:.0f} / "
          f"{g['N']['median']:.1f} / {g['N']['max']:.0f} frames; "
          f"L = {g['L_h']['min']:.1f} / {g['L_h']['median']:.1f} / "
          f"{g['L_h']['max']:.1f} h; median inter-frame gap = "
          f"{g['median_dt_h']['min']:.3f} / {g['median_dt_h']['median']:.3f} / "
          f"{g['median_dt_h']['max']:.3f} h; span/(N-1) = "
          f"{g['mean_interval_h']['min']:.3f} / {g['mean_interval_h']['median']:.3f} / "
          f"{g['mean_interval_h']['max']:.3f} h.")
    w("")

    r = d["gt_replays"]
    w("## 3. Replay accounting (GT layer)")
    w("")
    w(f"- Attempted units: {r['attempted']:,}; successful: {r['successful']:,}; "
      f"structurally infeasible: {r['failed']:,}")
    w(f"- Failure counts: `{json.dumps(r['failure_counts'])}`")
    w(f"- Oracle candidate evaluations: {r['oracle_candidate_evaluations']:,}")
    w(f"- Schedule wall clock, one process: {d['gt_wall_clock_s']:.2f} s")
    w("- Wall clock by method (s): " + ", ".join(
        f"{k}={v:.3f}" for k, v in sorted(r["schedule_wall_s_by_method"].items(),
                                          key=lambda kv: -kv[1])))
    w("")

    w("## 4. GT layer: equal-budget comparison")
    w("")
    w("Mean absolute area error E_A (pp), mean absolute leaf-count error E_N (leaves),")
    w("joint tolerance pass rate, and the plant-paired difference against U_0 at the")
    w("same K. `q90 z` is the empirical 90th percentile of")
    w("max(E_A/tau_A, E_N/tau_N); values <= 1 mean the tolerance is met by at least")
    w("90% of the plants in the common feasible set.")
    w("")
    w("| K | method | plants | mean E_A | mean E_N | joint pass | q90 z | diff vs U_0 | 95% CI | plan failures |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    tab = d["gt_schedule_table"]
    for k in KS:
        for m in METHOD_ORDER:
            row = tab.get(f"K{k}/{m}")
            if row is None:
                continue
            w(f"| {k} | {m} | {row['common_plants']} | {fmt(row['mean_E_A_pp'])} | "
              f"{fmt(row['mean_E_N_leaves'])} | {row['joint_pass_rate']:.3f} | "
              f"{fmt(row['q90_joint_z'], 3)} | {fmt(row['diff_vs_U0_pp'])} | "
              f"[{fmt(row['ci_lo_pp'])}, {fmt(row['ci_hi_pp'])}] | {row['plan_failures']} |")
    w("")
    amp = d["gt_phase_amplitude"]
    w("Widest gap between two families at the same budget (max minus min mean E_A):")
    for k in KS:
        a = d["gt_budget_spread"]["K%s/deployable" % k]
        b = d["gt_budget_spread"]["K%s/all" % k]
        w(f"- K={k}, deployable families: {fmt(a['spread_pp'])} pp "
          f"({a['worst']} {fmt(a['worst_pp'])} vs {a['best']} {fmt(a['best_pp'])}); "
          f"including the oracle: {fmt(b['spread_pp'])} pp "
          f"({b['worst']} vs {b['best']}).")
    w("")
    w("Phase amplitude (max minus min mean E_A across the three phases, pp):")
    for k in KS:
        w(f"- K={k}: {fmt(amp[k]['amplitude_pp'])} "
          f"(max {fmt(amp[k]['max_pp'])}, min {fmt(amp[k]['min_pp'])})")
    w("")
    w("Difference-of-differences `[E(K_low,m) - E(K_low,U_0)] - [E(K_high,m) - E(K_high,U_0)]`,")
    w("in pp; positive means the strategy is relatively worse at the smaller budget.")
    w("")
    w("| method | 5 vs 9 | 9 vs 15 | 5 vs 15 |")
    w("|---|---|---|---|")
    for m in METHOD_ORDER:
        if m in ("U_0", "oracle"):
            continue
        cells = []
        for pair in ("gt_interaction_5_9", "gt_interaction_9_15", "gt_interaction_5_15"):
            blk = d[pair].get(m)
            cells.append("n/a" if blk is None else fmt(blk["difference_pp"]))
        w(f"| {m} | " + " | ".join(cells) + " |")
    w("")
    flips = d["gt_paired_flips"]
    w("Paired budget changes for the uniform schedule `U_0` (same plants compared across")
    w("budgets, so the counts are not the same statement as the mean differences above):")
    for key in sorted(flips):
        b = flips[key]
        w(f"- {b['method']}: K={b['k_low']} to K={b['k_high']} over {b['plants']} plants: "
          f"{b['better_at_high']} with smaller E_A at the larger budget, "
          f"{b['worse_at_high']} with larger, {b['identical']} identical.")
    w("")

    j = d["joint_layer"]
    w("## 5. Joint RGB layer")
    w("")
    w(f"- Plants: {j['plants']}; per-plant records: {j['records']:,}; "
      f"area-eligible records: {j['area_eligible_records']:,}")
    w("- Area-eligible plants by role: " + ", ".join(
        f"{k}={v}" for k, v in sorted(j["plants_by_role"].items())))
    w(f"- Every joint-layer plant is also GT-area-eligible: "
      f"{j['plants_subset_of_gt_area_eligible']}")
    w(f"- Largest residual of the identity e_total = e_M + e_S + e_X: "
      f"{j['max_identity_residual']:.2e}")
    w("")
    w("Means over plants of the absolute signed terms of the decomposition, plus the")
    w("U_0 schedule error. `|e_M| > |e_S|` counts the plants whose sampling term is")
    w("smaller than the full-density measurement term, which is the pre-declared")
    w("dominance rule of the RGB pilot.")
    w("")
    w("| K | mean abs e_M | mean abs e_S | mean abs e_X | mean abs e_total | mean E_A | mean E_N | plants with \\|e_M\\| > \\|e_S\\| | joint pass |")
    w("|---|---|---|---|---|---|---|---|---|")
    per = j["per_budget_U0_and_fullRGB"]
    for k in JOINT_BUDGETS:
        b = per[k]
        w(f"| {k} | {fmt(b['mean_abs_e_M_pp'], 5)} | {fmt(b['mean_abs_e_S_pp'], 5)} | "
          f"{fmt(b['mean_abs_e_X_pp'], 5)} | {fmt(b['mean_abs_e_total_pp'], 5)} | "
          f"{fmt(b['mean_E_A_pp'], 5)} | {fmt(b['mean_E_N_leaves'])} | "
          f"{100 * b['share_measurement_dominant']:.1f}% | {b['joint_pass']}/{b['plants']} |")
    w("")
    w(f"- At full density the area term passes {j['area_pass_at_full']}/{j['plants']} and the")
    w(f"  leaf-count term passes {j['leaf_pass_at_full']}/{j['plants']}.")
    w("- Full-density joint failures:")
    w("")
    w("| plant | role | N | E_A (pp) | E_N (leaves) |")
    w("|---|---|---|---|---|")
    for rec in j["full_density_joint_failures"]:
        w(f"| {rec['plant']} | {rec['role']} | {rec['N']} | {fmt(rec['E_A_pp'])} | "
          f"{fmt(rec['E_N_leaves'], 3)} |")
    w("")
    w(f"- Deployability labels carried by the run manifests: "
      f"`{', '.join(j['deployability_labels'])}`")
    w("")

    g = d["gt_p1_gates"]
    w("## 6. Pre-declared P1 gates and the recorded decision")
    w("")
    w(f"- Decision recorded by the run manifest: `{g['decision']}`")
    w(f"- Protocols meeting the empirical 90% joint criterion: "
      f"{g['qualifying_protocols_n']} --- the six deterministic strategies at each of "
      f"the three budgets; the hindsight oracle and the random draws are excluded by "
      f"the gate definition.")
    w(f"- Minimum plants for the pilot gate: {g['minimum_plants_for_pilot_gate']}")
    w("- Boolean flags carried by the gate block: "
      + "; ".join(f"`{k}` = {v}" for k, v in sorted(g.items())
                  if isinstance(v, bool)))
    w("")

    q = d["gt_quantile_model"]
    w("## 7. Quantile error model (GT layer)")
    w("")
    w(f"- Status `{q['status']}`; target quantile {q['quantile']}; fitted on "
      f"{q['train_plants']} TRAIN plants and {q['train_replays']} replays; ridge penalty "
      f"{q['penalty']} on standardised coefficients ({q['penalty_definition']}); floors "
      f"{q['epsilon_area_pp']} pp and {q['epsilon_leaf']} leaves; fit wall clock "
      f"{q['fit_wall_s']:.3f} s.")
    w(f"- Features: {', '.join(q['features'])}.")
    w(f"- Minimum training plants {q['min_training_plants']}, minimum validation plants "
      f"per role {q['min_validation_plants_per_role']}; phase table development only: "
      f"{q['phase_table_development_only']}.")
    w("- Plant-weighted coverage of the nominal 90% prediction, by target and role:")
    w("")
    w("| target | role | plants | replays | coverage |")
    w("|---|---|---|---|---|")
    for t in sorted(q["validation_coverage"]):
        for role in sorted(q["validation_coverage"][t]):
            n = q["validation_sizes"][t][role]
            w(f"| {t} | {role} | {n[0]} | {n[1]} | "
              f"{q['validation_coverage'][t][role]:.3f} |")
    w("")

    w("## 8. Limitations and provenance recorded by the run manifest")
    w("")
    for item in d["gt_limitations"]:
        w(f"- {item}")
    s = d.get("superseded_run")
    if s:
        ar = s["actual_replays"]
        w(f"- Superseded run `{s['name']}` (source SHA-256 `{s['source_sha256']}`, "
          f"started {s['UTC_start']}, wall clock {s['runtime_wall_s']:.2f} s): "
          f"{ar['attempted']:,} units attempted, {ar['successful']:,} succeeded, "
          f"{ar['failed']:,} failed with counts "
          f"`{json.dumps(ar['failure_counts'])}`; its funnel was "
          f"{s['window_eligible_plants']} window-eligible and "
          f"{s['area_eligible_plants']} area-eligible plants.")
    w("")

    text = "\n".join(out) + "\n"
    (ROOT / "numbers.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
